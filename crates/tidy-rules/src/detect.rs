/// All detector ids, for `tidy detectors` and policy validation.
pub fn detector_ids() -> Vec<&'static str> {
    let mut v: Vec<&str> = ARTIFACTS.iter().map(|a| a.id).chain(PATHS.iter().map(|p| p.id)).collect();
    v.sort_unstable();
    v.dedup();
    v
}

fn valid_cachedir_tag(dir: &Path) -> bool {
    use std::io::Read;
    let mut buf = [0u8; 43];
    std::fs::File::open(dir.join("CACHEDIR.TAG")).and_then(|mut f| f.read_exact(&mut buf)).is_ok() && &buf == b"Signature: 8a477f597d28d172789f06886806bc55"
}

fn match_artifact(name: &[u8], flags: u16, pflags: u16, enabled: &dyn Fn(&str) -> bool, path: impl Fn() -> PathBuf) -> Option<&'static ArtifactRule> {
    for a in ARTIFACTS {
        if !enabled(a.id) {
            continue;
        }
        if !a.names.is_empty() && !a.names.iter().any(|x| x.as_bytes() == name) {
            continue;
        }
        if a.parent_any != 0 && pflags & a.parent_any == 0 {
            continue;
        }
        if a.self_any != 0 && flags & a.self_any == 0 {
            continue;
        }
        if a.names.is_empty() && a.self_any == 0 {
            continue;
        }
        if a.self_any == M_CACHEDIR_TAG && !valid_cachedir_tag(&path()) {
            continue;
        }
        return Some(a);
    }
    None
}

fn markers_of(dir: &Path) -> u16 {
    let mut f = 0;
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.flatten() {
            f |= marker(tidy_scan::path::path_bytes(Path::new(&e.file_name())));
        }
    }
    f
}

/// Classify a single directory without a full scan (for `tidy explain`).
/// Returns (detector id, what, hint, min_age seconds).
pub fn classify(path: &Path) -> Option<(&'static str, &'static str, &'static str, Option<i64>)> {
    let home = tidy_scan::path::home_dir();
    for r in PATHS {
        let base = home.join(r.rel);
        let hit = if r.children {
            path.parent() == Some(base.as_path())
                && !r.exclude.iter().any(|x| path.file_name().is_some_and(|n| n.to_string_lossy().starts_with(x)))
        } else {
            path == base
        };
        if hit {
            return Some((r.id, r.what, r.hint, Some(r.min_age_days * 86_400)));
        }
    }
    let name = tidy_scan::path::path_bytes(Path::new(path.file_name()?)).to_vec();
    let parent = path.parent()?;
    let all = |_: &str| true;
    match_artifact(&name, markers_of(path), markers_of(parent), &all, || path.to_path_buf()).map(|a| (a.id, a.what, a.hint, None))
}

pub fn detect(idx: &Index, cfg: &DetectConfig) -> Vec<Finding> {
    let enabled = |id: &str| !cfg.disabled.iter().any(|d| d == id);
    let home = tidy_scan::path::home_dir();
    // Resolve path rules to nodes present in this index.
    let mut path_hits: HashMap<u32, &PathRule> = HashMap::new();
    for r in PATHS.iter().filter(|r| enabled(r.id)) {
        let Some(n) = idx.lookup(&home.join(r.rel)) else { continue };
        if r.children {
            for &c in idx.children(n) {
                let name = idx.name(c);
                if r.exclude.iter().any(|x| name.starts_with(x.as_bytes())) {
                    continue;
                }
                path_hits.insert(c, r);
            }
        } else {
            path_hits.insert(n, r);
        }
    }

    let n = idx.nodes.len();
    let mut claimed = vec![false; n];
    let mut out = Vec::new();
    for i in 1..n {
        let node = &idx.nodes[i];
        let parent = node.parent as usize;
        if claimed[parent] {
            claimed[i] = true;
            continue;
        }
        let i32_ = i as u32;
        let hit = match path_hits.get(&i32_) {
            Some(r) => Some((r.id, r.what, r.hint, Some(r.min_age_days * 86_400))),
            None => match_artifact(idx.name(i32_), node.flags, idx.nodes[parent].flags, &enabled, || idx.path(i32_))
                .map(|a| (a.id, a.what, a.hint, None)),
        };
        let Some((id, what, hint, min_age)) = hit else { continue };
        claimed[i] = true;
        if node.size(SizeKind::Alloc) < cfg.min_size {
            continue;
        }
        out.push(Finding {
            node: i32_,
            path: idx.path(i32_),
            detector: id,
            action: cfg.action.unwrap_or(Action::Delete),
            reason: what.to_string(),
            hint,
            min_age,
        });
    }
    out.sort_by_key(|f| std::cmp::Reverse(idx.nodes[f.node as usize].private));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    #[test]
    fn finds_artifacts_outermost_only() {
        let t = tempfile::tempdir().unwrap();
        let r = t.path();
        let big = vec![0u8; 2_000_000];
        // cargo project with target
        fs::create_dir_all(r.join("rs/target/debug")).unwrap();
        fs::write(r.join("rs/Cargo.toml"), "").unwrap();
        fs::write(r.join("rs/target/debug/app"), &big).unwrap();
        // a "target" without Cargo.toml must NOT match
        fs::create_dir_all(r.join("notes/target")).unwrap();
        fs::write(r.join("notes/target/goals.md"), &big).unwrap();
        // node_modules with nested node_modules
        fs::create_dir_all(r.join("web/node_modules/a/node_modules/b")).unwrap();
        fs::write(r.join("web/package.json"), "{}").unwrap();
        fs::write(r.join("web/node_modules/a/node_modules/b/index.js"), &big).unwrap();
        // venv anywhere
        fs::create_dir_all(r.join("py/.venv/lib")).unwrap();
        fs::write(r.join("py/.venv/pyvenv.cfg"), "home = /usr").unwrap();
        fs::write(r.join("py/.venv/lib/torch.so"), &big).unwrap();
        // CACHEDIR.TAG with valid and invalid signatures
        fs::create_dir_all(r.join("c1")).unwrap();
        fs::write(r.join("c1/CACHEDIR.TAG"), "Signature: 8a477f597d28d172789f06886806bc55\n").unwrap();
        fs::write(r.join("c1/blob"), &big).unwrap();
        fs::create_dir_all(r.join("c2")).unwrap();
        fs::write(r.join("c2/CACHEDIR.TAG"), "nope").unwrap();
        fs::write(r.join("c2/blob"), &big).unwrap();
        // tiny artifact under threshold
        fs::create_dir_all(r.join("tiny/target")).unwrap();
        fs::write(r.join("tiny/Cargo.toml"), "").unwrap();
        fs::write(r.join("tiny/target/x"), b"1").unwrap();

        let idx = tidy_scan::scan(r, &Default::default()).unwrap();
        let f = detect(&idx, &DetectConfig::default());
        let got: Vec<(String, &str)> = f.iter().map(|x| (x.path.strip_prefix(&idx.root).unwrap().display().to_string(), x.detector)).collect();
        let mut got_sorted = got.clone();
        got_sorted.sort();
        assert_eq!(
            got_sorted,
            vec![
                ("c1".to_string(), "cachedir-tag"),
                ("py/.venv".to_string(), "python-venv"),
                ("rs/target".to_string(), "cargo-target"),
                ("web/node_modules".to_string(), "node-modules"),
            ],
            "{got:?}"
        );
        assert!(f.iter().all(|x| x.action == Action::Delete));
        // disabling a detector
        let f2 = detect(&idx, &DetectConfig { disabled: vec!["node-modules".into()], ..Default::default() });
        assert!(!f2.iter().any(|x| x.detector == "node-modules"));
        assert!(detector_ids().len() >= 10);
    }
}
