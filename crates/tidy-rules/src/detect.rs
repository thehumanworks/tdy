//! L1 detectors: deterministic recognisers for regenerable artifacts.
//!
//! Everything here runs on the scan index alone — marker files seen during
//! the scan are recorded as node flags — so detection costs no extra I/O
//! beyond validating a `CACHEDIR.TAG` signature when one is present.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use tidy_plan::Action;
use tidy_scan::index::node_flags::*;
use tidy_scan::{Index, SizeKind};

#[derive(Clone, Debug)]
pub struct Finding {
    pub node: u32,
    pub path: PathBuf,
    pub detector: &'static str,
    pub action: Action,
    pub reason: String,
    /// How the artifact comes back.
    pub hint: &'static str,
    /// Minimum age required by this detector (raises the guard default).
    pub min_age: Option<i64>,
}

#[derive(Clone, Debug)]
pub struct DetectConfig {
    /// Ignore findings smaller than this (allocated bytes).
    pub min_size: u64,
    /// Replace the default action (e.g. `trash` instead of `delete`).
    pub action: Option<Action>,
    /// Detector ids to skip.
    pub disabled: Vec<String>,
}

impl Default for DetectConfig {
    fn default() -> Self {
        DetectConfig { min_size: 1_000_000, action: None, disabled: Vec::new() }
    }
}

